#!/usr/bin/env python3
"""Generate sql/092_zone_pricing_seed.sql from regional-expansion-prices.json.

Reads the approved plan-A price draft (docs/billing-regional-pricing/
regional-expansion-prices.json) and emits the idempotent seed migration for
pricing_zones / pricing_country_routes / pricing_zone_prices (091 tables).

Rows ship with is_enabled=0 / stripe_price_id NULL — nothing is sellable until
Price ids are backfilled and countries enabled. Counts are asserted against
the spec (77 prices, 110 local-currency amounts, 11 routes, 7 zones) and the
script fails if the draft drifts.

Usage: python3 scripts/gen_zone_pricing_seed.py [--out sql/092_zone_pricing_seed.sql]
"""

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PRICES_JSON = REPO / "docs/billing-regional-pricing" / "regional-expansion-prices.json"
DEFAULT_OUT = REPO / "sql" / "092_zone_pricing_seed.sql"

EXPECTED_COUNTRIES = 11
EXPECTED_ZONES = 7
EXPECTED_PRICES = 77
EXPECTED_AMOUNTS = 110

SKU_KINDS = {
    "pro_trial_to_monthly": "subscription_plan",
    "basic_monthly": "subscription_plan",
    "basic_yearly": "subscription_plan",
    "plus_monthly": "subscription_plan",
    "plus_yearly": "subscription_plan",
    "pro_monthly": "subscription_plan",
    "pro_yearly": "subscription_plan",
    "addon_assignment_3": "addon",
    "addon_detection_5": "addon",
    "addon_humanizer_3": "addon",
    "study_pass_subscription_30d": "study_pass",
}


def sql_str(value: str) -> str:
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def main() -> int:
    draft = json.loads(PRICES_JSON.read_text(encoding="utf-8"))
    routes = draft["countryRoutes"]
    versions = draft["activeVersions"]
    catalog = draft["catalogs"][versions["Z080"]]
    zones = catalog["zones"]

    assert len(routes) == EXPECTED_COUNTRIES, f"routes: {len(routes)}"
    assert len(zones) == EXPECTED_ZONES, f"zones: {len(zones)}"
    assert len({r["zone"] for r in routes.values()}) == EXPECTED_ZONES, "route zones mismatch"

    total_prices = 0
    total_amounts = 0
    blocks = []

    zone_label = {}
    for country in sorted(routes):
        route = routes[country]
        zone_label.setdefault(route["zone"], []).append(route["label"])

    zone_rows = []
    for zone_code in sorted(zones):
        meta = zones[zone_code]
        label = "/".join(zone_label[zone_code])
        zone_rows.append(
            f"({sql_str(zone_code)}, {sql_str(label)}, {sql_str(str(meta['referenceFactor']))}, "
            f"{sql_str(versions[zone_code])}, 0)"
        )
        price_rows = []
        for sku_code, price in sorted(meta["prices"].items()):
            total_prices += 1
            currency_amounts = {
                cur: {"amountMinor": opt["amountMinor"]}
                for cur, opt in price.get("currencyAmounts", {}).items()
            }
            total_amounts += len(currency_amounts)
            interval = price.get("interval")
            price_rows.append(
                f"({sql_str(zone_code)}, {sql_str(versions[zone_code])}, {sql_str(sku_code)}, "
                f"{sql_str(SKU_KINDS[sku_code])}, NULL, NULL, {sql_str(price['priceType'])}, "
                f"{sql_str(interval) if interval else 'NULL'}, {price.get('intervalCount') or 1}, "
                f"{price['expectedDefaultAmountMinor']}, "
                f"{sql_str(json.dumps(currency_amounts, separators=(',', ':'), sort_keys=True))}, "
                f"{sql_str(price['renewalSku']) if price.get('renewalSku') else 'NULL'}, 1)"
            )
        blocks.append((zone_code, price_rows))

    assert total_prices == EXPECTED_PRICES, f"prices: {total_prices}"
    assert total_amounts == EXPECTED_AMOUNTS, f"amounts: {total_amounts}"

    route_rows = []
    for country in sorted(routes):
        route = routes[country]
        route_rows.append(
            f"({sql_str(country)}, {sql_str(route['zone'])}, {sql_str(route['currency'])}, "
            f"{sql_str(route['label'])}, 0)"
        )

    lines = [
        "-- GENERATED by scripts/gen_zone_pricing_seed.py — do not edit by hand.",
        "-- Source: docs/billing-regional-pricing/regional-expansion-prices.json",
        f"-- Counts asserted: {EXPECTED_COUNTRIES} routes / {EXPECTED_ZONES} zones / "
        f"{EXPECTED_PRICES} price bindings / {EXPECTED_AMOUNTS} local-currency amounts.",
        "-- Idempotent via ON DUPLICATE KEY UPDATE; re-running never resets backfilled",
        "-- stripe_price_id values or enabled flags. All switches ship OFF.",
        "",
        "USE studyagent;",
        "",
        "-- Zones (is_active=0: zone-level sale switch, off until preflight passes)",
        "INSERT INTO pricing_zones (zone_code, label, reference_factor, active_version, is_active) VALUES",
        ",\n".join("    " + r for r in zone_rows),
        "ON DUPLICATE KEY UPDATE label=VALUES(label), reference_factor=VALUES(reference_factor);",
        "",
        "-- Country routes (is_enabled=0: enable per country only after the zone's 11 SKUs",
        "-- are backfilled and preflight is green)",
        "INSERT INTO pricing_country_routes (country_code, zone_code, currency, label, is_enabled) VALUES",
        ",\n".join("    " + r for r in route_rows),
        "ON DUPLICATE KEY UPDATE zone_code=VALUES(zone_code), currency=VALUES(currency), label=VALUES(label);",
        "",
        "-- Price registry draft rows (stripe_price_id NULL = not sellable yet).",
        "-- currency_amounts is the preflight cross-check baseline; runtime amounts are",
        "-- still read live from Stripe and compared against it.",
    ]
    for zone_code, price_rows in blocks:
        lines += [
            f"-- {zone_code} ({versions[zone_code]})",
            "INSERT INTO pricing_zone_prices (zone_code, price_version, sku_code, sku_kind, "
            "stripe_price_id, stripe_product_id, price_type, billing_interval, interval_count, "
            "usd_default_amount_minor, currency_amounts, renewal_sku_code, is_active) VALUES",
            ",\n".join("    " + r for r in price_rows),
            "ON DUPLICATE KEY UPDATE currency_amounts=VALUES(currency_amounts), "
            "usd_default_amount_minor=VALUES(usd_default_amount_minor), "
            "renewal_sku_code=VALUES(renewal_sku_code);",
            "",
        ]

    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"zones={EXPECTED_ZONES} routes={EXPECTED_COUNTRIES} prices={total_prices} amounts={total_amounts}")
    print(f"written: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
